import { test, expect } from '@playwright/test';

const deployment = process.env.WEXA_PHP_SMOKE_URL?.replace(/\/$/, '');
const password = process.env.ADMIN_E2E_PASSWORD;
test.skip(!deployment || !password, 'Requires an explicitly isolated installed PHP deployment.');
test('PHP deployment preserves branded navigation, Atlas form, assets, query history and admin session', async ({ page, request }) => {
  const prefix = new URL(deployment!).pathname.replace(/\/$/, '');
  const url = (path: string) => deployment + path;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url('/tr'));
  await expect(page).toHaveTitle(/WexaShelf/);
  await expect(page.getByRole('link', { name: 'WexaShelf', exact: true })).toBeVisible();
  const credit = page.getByRole('contentinfo').getByRole('link', { name: 'Softwexa', exact: true });
  await expect(credit).toBeVisible();
  await expect(credit).toHaveAttribute('href', 'https://softwexa.com');
  const lock = await request.get(url('/kurulum?locale=tr')); // Explicit Turkish installer message.
  expect(lock.status()).toBe(409);
  expect(await lock.text()).toContain('Kurulum kilitli');
  expect((await request.get(url('/api/admin'))).status()).toBe(401);
  await page.goto(url('/ayarlar'));
  await page.getByRole('button', { name: /^Temayı kullan\s*:\s*Kobalt Atlas$/ }).click();
  await page.goto(url('/tr'));
  const form = page.locator('form.atlas-search');
  await expect(form).toHaveAttribute('action', prefix + '/kesfet');
  await form.getByLabel('Ne yapmak istiyorsun?').fill('Notion');
  await form.getByRole('button', { name: 'Ara' }).click();
  await expect(page).toHaveURL(url('/kesfet?q=Notion'));
  await expect(page.locator('.catalog-card h2')).toHaveText('Notion');
  const image = page.locator('.catalog-card img').first();
  await expect(image).toBeVisible();
  expect(await image.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.goto(url('/kesfet?platform=android,windows&mode=all'));
  await expect(page.locator('.catalog-card')).toHaveCount(8);
  await page.locator('.advanced-filters summary').click();
  await page.getByLabel('Platform eşleşmesi').selectOption('any');
  await expect(page.locator('.catalog-card')).toHaveCount(10);
  expect(new URL(page.url()).pathname).toBe(prefix + '/kesfet');
  await page.goBack();
  await expect(page.locator('.catalog-card')).toHaveCount(8);
  await page.goto(url('/ayarlar'));
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Etkin temayı indir' }).click();
  expect((await download).suggestedFilename()).toBe('kobalt-atlas.json');
  await page.addInitScript(() => localStorage.setItem('wexashelf.admin.locale', 'tr'));
  await page.goto(url('/admin'));
  await page.getByLabel('Yönetici parolası').fill(password!);
  await page.getByRole('button', { name: 'Giriş yap', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'İçeriğin kontrolü sende.' })).toBeVisible();
  expect((await page.request.get(url('/api/admin'))).status()).toBe(200);
  await page.getByRole('button', { name: 'Çıkış', exact: true }).click();
  await expect(page.getByLabel('Yönetici parolası')).toBeVisible();
  expect((await page.request.get(url('/api/admin'))).status()).toBe(401);
  expect(errors).toEqual([]);
});
