import { test, expect } from '@playwright/test';

const baseURL = process.env.ADMIN_E2E_BASE_URL;
const password = process.env.ADMIN_E2E_PASSWORD;
test.use({ baseURL });
test.describe('isolated unsaved editor selections', () => {
  test.skip(!baseURL || !password, 'Requires an isolated synthetic PHP sample catalog and disposable owner password.');
  test('bulk picker stages changes and inline references preserve exact text', async ({ page }) => {
    test.setTimeout(60000);
    const login = await page.request.post(`${baseURL}/api/admin/login`, { headers: { Origin: new URL(baseURL!).origin }, data: { password } });
    expect(login.status()).toBe(200);
    await page.goto(`${baseURL!.replace(/\/$/, '')}/admin`);
    await page.getByRole('button', { name: 'Content', exact: true }).click();
    await page.locator('.admin-kind-tabs').getByRole('button', { name: 'Article', exact: true }).click();
    await page.getByRole('button', { name: 'New Article', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const related = page.getByRole('button', { name: /^Related app IDs/ });
    const initial = await related.innerText();
    await related.click();
    const query = dialog.getByRole('combobox').first();
    await expect(query).toBeFocused();
    await expect(dialog.locator('[role=option]').first()).toBeVisible();
    const select = dialog.getByRole('button', { name: 'Select displayed', exact: true });
    const clear = dialog.getByRole('button', { name: 'Clear displayed', exact: true });
    await select.click();
    expect(await dialog.locator('ol li').count()).toBeGreaterThan(1);
    await query.fill('Notion');
    await expect(dialog.locator('[role=option]')).toHaveCount(1);
    await clear.click();
    await expect(dialog.locator('ol li strong').filter({ hasText: /^Notion$/ })).toHaveCount(0);
    expect(await dialog.locator('ol li').count()).toBeGreaterThan(0);
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(related).toBeFocused();
    expect(await related.innerText()).toBe(initial);
    await related.click();
    await query.fill('Notion');
    await expect(dialog.locator('[role=option]')).toHaveCount(1);
    await select.click();
    await dialog.getByRole('button', { name: 'Apply', exact: true }).click();
    await expect(related).toContainText('Notion');

    const paragraphs = page.getByLabel('Section 1 paragraphs', { exact: true });
    const inline = page.getByRole('button', { name: /^Find an app to reference/ });
    const original = 'Before 😀 selected after 🧭';
    await paragraphs.fill(original);
    await paragraphs.evaluate((field: HTMLTextAreaElement) => { field.focus(); field.setSelectionRange(10, 18); field.dispatchEvent(new Event('select', { bubbles: true })); });
    const choose = async (apply: boolean) => {
      await inline.click();
      await expect(dialog.getByRole('button', { name: 'Select displayed', exact: true })).toHaveCount(0);
      await query.fill('Notion');
      await expect(dialog.locator('[role=option]')).toHaveCount(1);
      await dialog.locator('[role=option]').click();
      await dialog.getByRole('button', { name: apply ? 'Apply' : 'Cancel', exact: true }).click();
    };
    await choose(false);
    await expect(paragraphs).toHaveValue(original);
    await choose(true);
    const code = '[app id="notion"]';
    await expect(paragraphs).toHaveValue(original.slice(0, 10) + code + original.slice(18));
    await expect(paragraphs).toBeFocused();
    await choose(true);
    await expect(paragraphs).toHaveValue(original.slice(0, 10) + code + code + original.slice(18));
    await page.getByRole('button', { name: 'Add section', exact: true }).click();
    const second = page.getByLabel('Section 2 paragraphs', { exact: true });
    await second.fill('Second 😀 tail');
    await second.evaluate((field: HTMLTextAreaElement) => { field.focus(); field.setSelectionRange(7, 7); field.dispatchEvent(new Event('select', { bubbles: true })); });
    const sectionChoice = page.getByRole('combobox', { name: 'Insert into section', exact: true });
    await expect(sectionChoice).toHaveValue('1');
    await choose(true);
    await expect(second).toHaveValue('Second ' + code + '😀 tail');
    await expect(second).toBeFocused();
    await sectionChoice.selectOption('0');
    const firstBeforeFallback = await paragraphs.inputValue();
    await choose(true);
    await expect(paragraphs).toHaveValue(firstBeforeFallback + '\n\n' + code);
    await expect(second).toHaveValue('Second ' + code + '😀 tail');
    await page.setViewportSize({ width: 390, height: 844 });
    await related.click();
    await expect(select).toBeEnabled();
    await select.focus();
    await select.press('Space');
    expect(await dialog.locator('ol li').count()).toBeGreaterThan(1);
    const bounds = await dialog.evaluate(element => ({ width: element.clientWidth, scroll: element.scrollWidth, viewport: innerWidth, page: document.documentElement.scrollWidth }));
    expect(bounds.scroll).toBeLessThanOrEqual(bounds.width + 1);
    expect(bounds.page).toBeLessThanOrEqual(bounds.viewport + 1);
    await clear.focus();
    await clear.press('Space');
    await expect(dialog.locator('ol li')).toHaveCount(0);
    await page.keyboard.press('Escape');
    await expect(related).toBeFocused();
    await page.setViewportSize({ width: 1280, height: 720 });
    await page.getByRole('button', { name: 'AI content studio', exact: true }).click();
    await page.getByRole('button', { name: /^Source apps/ }).click();
    await expect(dialog.locator('[role=option]').first()).toBeVisible();
    await select.click();
    await expect(dialog.locator('ol li')).toHaveCount(4);
    await expect(select).toBeDisabled();
    await clear.click();
    await expect(dialog.locator('ol li')).toHaveCount(0);
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();

  });
});
